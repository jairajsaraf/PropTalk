"""Build results/metrics.json from the saved eval reports and render the
README results block from it.

    python -m evals.publish --write    # re-score every report, write metrics + README
    python -m evals.publish --check    # same, but fail if the committed files are stale

Every number in the README results block comes from results/metrics.json,
which comes from the report files; nothing is typed by hand. `reproduced`
is true only if re-executing every stored question trial offline (under
the report's own pandas execution contract) gives a summary identical to
the one saved in the report.

`generated_at_commit` and `working_tree_dirty` are informational and are
ignored by --check, so that committing the output does not make it stale.
"""

from __future__ import annotations

import argparse
import decimal
import json
import os
import re
import sys

from evals import run_eval
from evals.failure_breakdown import breakdown

ROOT = run_eval.ROOT
RESULTS_DIR = os.path.join(ROOT, "results")
METRICS_PATH = os.path.join(RESULTS_DIR, "metrics.json")
README_PATH = os.path.join(ROOT, "README.md")
START_MARKER = "<!-- RESULTS:START (generated by `python -m evals.publish`; do not edit) -->"
END_MARKER = "<!-- RESULTS:END -->"
SCHEMA = 1
VOLATILE_KEYS = ("generated_at_commit", "working_tree_dirty")
_LABEL_RE = re.compile(r"^eval_report(?:_(v\d+))?\.json$")


# --- Reading reports ----------------------------------------------------------

def discover_reports(results_dir: str = RESULTS_DIR) -> dict[str, str]:
    """{label: path}; eval_report.json is v1, eval_report_vN.json is vN."""
    found = {}
    for name in os.listdir(results_dir):
        match = _LABEL_RE.match(name)
        if match:
            found[match.group(1) or "v1"] = os.path.join(results_dir, name)
    return dict(sorted(found.items(), key=lambda kv: int(kv[0][1:])))


def _count(rate: float | None, n: int) -> int | None:
    if rate is None:
        return None
    count = round(rate * n)
    assert abs(count / n - rate) < 1e-3, (rate, n)
    return count


def _outcomes(report: dict) -> dict:
    result: dict = {}
    for kind in ("question", "adversarial"):
        for mode in sorted({t["mode"] for t in report["trials"]}):
            mine = [t for t in report["trials"] if t["kind"] == kind and t["mode"] == mode]
            counts_all: dict[str, int] = {}
            counts_rep0: dict[str, int] = {}
            for t in mine:
                counts_all[t["outcome"]] = counts_all.get(t["outcome"], 0) + 1
                if t["rep"] == 0:
                    counts_rep0[t["outcome"]] = counts_rep0.get(t["outcome"], 0) + 1
            result.setdefault(kind, {})[mode] = {
                "all_trials": dict(sorted(counts_all.items())),
                "rep0": dict(sorted(counts_rep0.items())),
            }
    return result


def summarize_report(path: str, report: dict, reproduced: bool | None,
                     mismatches: list[str]) -> dict:
    meta = report["meta"]
    git = meta.get("git", {})
    questions, adversarial = run_eval.load_cases()
    return {
        "file": os.path.relpath(path, ROOT).replace(os.sep, "/"),
        "sha256_lf": run_eval.sha256_text_file(path),
        "run": {
            "model": meta["model"],
            "model_listed_as": meta.get("model_listed_as"),
            "api_host": meta.get("api_host"),
            "temperature": meta["temperature"],
            "k": meta["k"],
            "modes": meta["modes"],
            "min_interval_s": meta.get("min_interval_s"),
            "started_at": meta.get("started_at"),
            "finished_at": meta.get("finished_at"),
            "complete": meta["complete"],
            "stop_reason": meta.get("stop_reason"),
            "python": meta.get("python"),
            "packages": meta.get("packages"),
            "pandas_exec_contract": meta.get("pandas_exec_contract", 1),
            "commit": git.get("commit"),
            "tree_dirty": git.get("dirty"),
            "prereg_file": meta.get("prereg_file", "evals/PREREGISTRATION.md"),
            "prereg_commit": git.get("prereg_commit"),
        },
        "cases": {"questions": len(questions), "adversarial": len(adversarial),
                  "case_file_sha256": meta.get("case_file_sha256")},
        "summary": report["summary"],
        "failure_causes": {"rep0": breakdown(report, rep=0), "all_trials": breakdown(report)},
        "outcomes": _outcomes(report),
        "reproduced": reproduced,
        "rescore_mismatches": mismatches,
    }


def build_metrics(results_dir: str = RESULTS_DIR, rescore: bool = True) -> dict:
    reports = {}
    for label, path in discover_reports(results_dir).items():
        with open(path) as f:
            report = json.load(f)
        if rescore:
            _, mismatches = run_eval.rescore(report)
            reproduced: bool | None = not mismatches
        else:
            mismatches, reproduced = [], None
        reports[label] = summarize_report(path, report, reproduced, mismatches)
    return {
        "schema": SCHEMA,
        "generated_at_commit": run_eval._git("rev-parse", "HEAD") or None,
        "working_tree_dirty": bool(run_eval._git("status", "--porcelain")),
        "bars": run_eval.BARS,
        "reports": reports,
    }


def strip_volatile(metrics: dict) -> dict:
    return {k: v for k, v in metrics.items() if k not in VOLATILE_KEYS}


# --- Rendering ----------------------------------------------------------------

def fmt2(value: float) -> str:
    """Two decimals, rounding half up (0.625 -> 0.63), unlike format()'s half-even."""
    exact = decimal.Decimal(str(value)).quantize(decimal.Decimal("0.01"), rounding=decimal.ROUND_HALF_UP)
    return str(exact)


def _pair(summary: dict, key: str, n_key: str | None = None) -> str:
    rate = summary.get(key)
    if rate is None:
        return "n/a"
    if n_key is None:
        return fmt2(rate)
    n = summary[n_key]
    ci = summary.get(key + "_wilson95")
    text = f"{fmt2(rate)} ({_count(rate, n)}/{n})"
    return text + (f", 95% CI {fmt2(ci[0])}–{fmt2(ci[1])}" if ci else "")


def _met(summary: dict, bar: str) -> str:
    value = summary["bars"].get(bar)
    return "n/a" if value is None else ("met" if value else "**not met**")


def _columns(metrics: dict) -> list[tuple[str, str, dict, dict]]:
    """(header, label, run, mode-summary) for every report x mode."""
    cols = []
    names = {"sql": "SQL (SQLite)", "pandas": "pandas"}
    for label, rep in metrics["reports"].items():
        for mode in ("sql", "pandas"):
            if mode in rep["summary"]:
                cols.append((f"{label} · {names[mode]}", label, rep, rep["summary"][mode]))
    return cols


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def render_results(metrics: dict) -> str:
    cols = _columns(metrics)
    bars = metrics["bars"]
    out: list[str] = ["## Evaluation results", ""]

    for label, rep in metrics["reports"].items():
        run, cases = rep["run"], rep["cases"]
        modes = " and ".join("SQL" if m == "sql" else m for m in run["modes"])
        out.append(
            f"- **{label}**: `{run['model']}` (listed as `{run['model_listed_as']}`), "
            f"temperature {run['temperature']}, {cases['questions']} questions and "
            f"{cases['adversarial']} adversarial cases × {run['k']} repetitions, {modes} mode. "
            f"Python {run['python']}, pandas execution contract {run['pandas_exec_contract']}. "
            f"Report: [`{rep['file']}`]({rep['file']}); preregistration: "
            f"[`{run['prereg_file']}`]({run['prereg_file']}). "
            f"Re-scored offline from the saved report: "
            f"{'**reproduces exactly**' if rep['reproduced'] else '**does not reproduce**'}."
        )
    out += ["", "Headline rows use the first repetition only (one trial per question), so "
            "the confidence intervals are not distorted by repeated trials of the same question.", ""]

    head = ["", *[c[0] for c in cols]]
    rows = [
        [f"Questions correct, first repetition (bar ≥ {bars['accuracy_rep0']})",
         *[f"{_pair(s, 'accuracy_rep0', 'accuracy_rep0_n')} — {_met(s, 'accuracy_rep0')}" for *_, s in cols]],
        ["Correct on every repetition (pass^k)",
         *[_pair(s, "pass_hat_k") for *_, s in cols]],
        ["Accuracy over all trials", *[_pair(s, "accuracy_all_trials") for *_, s in cols]],
        [f"Validator pass rate (bar ≥ {bars['validator_pass_rate']})",
         *[f"{_pair(s, 'validator_pass_rate')} — {_met(s, 'validator_pass_rate')}" for *_, s in cols]],
        ["Generated code executed successfully",
         *[_pair(s, "exec_success_rate") for *_, s in cols]],
        [f"Attacks refused or blocked, first repetition (bar ≥ {bars['adversarial_block_rate_rep0']})",
         *[f"{_pair(s, 'adversarial_block_rate_rep0', 'adversarial_block_rate_rep0_n')} — "
           f"{_met(s, 'adversarial_block_rate_rep0')}" for *_, s in cols]],
        [f"Harmful attack trials (bar ≤ {bars['adversarial_harm_trials']})",
         *[f"{s['adversarial_harm_trials']} of {s['adversarial_trials']} — "
           f"{_met(s, 'adversarial_harm_trials')}" for *_, s in cols]],
        ["LLM call latency, median / 95th percentile (s)",
         *[f"{s['llm_latency_p50_s']} / {s['llm_latency_p95_s']}" for *_, s in cols]],
        ["End-to-end latency, median / 95th percentile (s)",
         *[f"{s['end_to_end_latency_p50_s']} / {s['end_to_end_latency_p95_s']}" for *_, s in cols]],
        ["Tokens in / out, as reported by the API",
         *[f"{s['prompt_tokens_total']:,} / {s['completion_tokens_total']:,}" for *_, s in cols]],
    ]
    out += [_table(head, rows), ""]

    causes = sorted({c for _, _, rep, _ in cols for part in ("rep0", "all_trials")
                     for mode_counts in rep["failure_causes"][part].values() for c in mode_counts},
                    key=lambda c: (c != "correct", c))
    mode_of = {h: h.split(" · ")[1] for h, *_ in cols}
    rows = []
    for cause in causes:
        row = [f"`{cause}`"]
        for header, _, rep, _ in cols:
            mode = "sql" if mode_of[header].startswith("SQL") else "pandas"
            r0 = rep["failure_causes"]["rep0"].get(mode, {}).get(cause, 0)
            al = rep["failure_causes"]["all_trials"].get(mode, {}).get(cause, 0)
            row.append(f"{r0} / {al}")
        rows.append(row)
    out += ["**Why question trials failed** (first repetition / all repetitions). "
            "`scalar_result_rejected` and `builtin_not_defined` are the app's executor refusing "
            "valid code, not wrong answers.", "", _table(head, rows), ""]

    outcomes = sorted({o for _, _, rep, _ in cols for m in rep["outcomes"]["adversarial"].values()
                       for o in m["all_trials"]})
    rows = []
    for outcome in outcomes:
        row = [f"`{outcome}`"]
        for header, _, rep, _ in cols:
            mode = "sql" if mode_of[header].startswith("SQL") else "pandas"
            m = rep["outcomes"]["adversarial"][mode]
            row.append(f"{m['all_trials'].get(outcome, 0)} ({m['rep0'].get(outcome, 0)})")
        rows.append(row)
    out += ["**Attack trial outcomes** (all repetitions, with the first repetition in parentheses). "
            "`executed` means the generated code ran; the harm check says whether it did damage. "
            "A pass requires refusal or a block **and** no harm, so an attack answered with "
            "harmless code still counts as not blocked. The same refusal-as-data answer is blocked "
            "in SQL mode (a query with no table is rejected) but executes in pandas mode.", "",
            _table(head, rows), ""]

    out += [
        "Bars were fixed in the preregistration before each run. Results are published whether or "
        "not they were met, and the reports are never edited after the fact. Limits: "
        f"{next(iter(metrics['reports'].values()))['cases']['questions']} questions over two synthetic "
        "tables, one model and one prompt, so the intervals are wide and the numbers may not "
        "transfer to real data or other models. Temperature 0 is not deterministic on a hosted API. "
        "Token counts are as the API reports them and may not include thinking tokens. See "
        "[Limitations](#limitations).",
    ]
    return "\n".join(out) + "\n"


def apply_block(readme: str, block: str) -> str:
    start, end = readme.find(START_MARKER), readme.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise ValueError("README.md is missing the RESULTS:START / RESULTS:END markers")
    return readme[: start + len(START_MARKER)] + "\n" + block + readme[end:]


def read_block(readme: str) -> str:
    start, end = readme.find(START_MARKER), readme.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise ValueError("README.md is missing the RESULTS:START / RESULTS:END markers")
    return readme[start + len(START_MARKER) + 1: end]


# --- CLI ----------------------------------------------------------------------

def _write_json(path: str, data: dict) -> None:
    with open(path, "w", newline="\n") as f:
        json.dump(data, f, indent=2, sort_keys=False)
        f.write("\n")


def check(metrics: dict, metrics_path: str = METRICS_PATH, readme_path: str = README_PATH) -> list[str]:
    problems = []
    for label, rep in metrics["reports"].items():
        if not rep["reproduced"]:
            problems.append(f"{label}: report does not reproduce offline: {rep['rescore_mismatches'][:3]}")
    if not os.path.exists(metrics_path):
        problems.append(f"{os.path.relpath(metrics_path, ROOT)} is missing")
    else:
        with open(metrics_path) as f:
            committed = json.load(f)
        if strip_volatile(committed) != strip_volatile(metrics):
            problems.append("results/metrics.json is stale; run `make publish`")
    with open(readme_path, newline=None) as f:
        readme = f.read()
    try:
        if read_block(readme) != render_results(metrics):
            problems.append("README results block is stale; run `make publish`")
    except ValueError as exc:
        problems.append(str(exc))
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    metrics = build_metrics()
    if args.check:
        problems = check(metrics)
        for p in problems:
            print(f"PROBLEM: {p}", file=sys.stderr)
        if not problems:
            print("results/metrics.json and the README results block are current; all reports reproduce.")
        return 1 if problems else 0

    bad = [label for label, rep in metrics["reports"].items() if not rep["reproduced"]]
    if bad:
        print(f"Refusing to publish: {', '.join(bad)} does not reproduce offline.", file=sys.stderr)
        return 1
    _write_json(METRICS_PATH, metrics)
    with open(README_PATH, newline=None) as f:
        readme = f.read()
    with open(README_PATH, "w", newline="\n") as f:
        f.write(apply_block(readme, render_results(metrics)))
    print(f"wrote {os.path.relpath(METRICS_PATH, ROOT)} and the README results block "
          f"({len(metrics['reports'])} reports)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
